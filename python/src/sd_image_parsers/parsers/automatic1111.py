"""AUTOMATIC1111's stable-diffusion-webui and the tools that write its format."""

from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Tuple

from .._util import js_trim, load_json
from ..data import Generators, Model, Prompt, PromptInfo, Sampler
from ..exceptions import ParserError
from ._base import Parser, pop_keys

SAMPLER_PARAMS = ["Sampler", "CFG scale", "Seed", "Steps", "ENSD", "Schedule type"]
REPLACEMENT_RULES = [("Schedule type", "scheduler")]

_KEY = re.compile(r"\s*([^,:\n]+?):\s*")


class AUTOMATIC1111Parser(Parser):
    """Parser for images generated by AUTOMATIC1111's stable-diffusion-webui or similar"""

    generator = Generators.AUTOMATIC1111

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        # CivitAI writes the parameters to the EXIF UserComment of its PNG files
        parameter_string = parameters.get("parameters") if parameters.get("parameters") is not None else parameters.get("UserComment")
        if not isinstance(parameter_string, str):
            raise ParserError("error reading parameter string")
        lines = parameter_string.split("\n")

        info_index, sampler_info, metadata = _get_sampler_info(lines)
        # SD.Next repeats the prompts as templates before the settings
        prompt_lines = lines[:info_index]
        template_index = next(
            (i for i, line in enumerate(prompt_lines) if re.match(r"(?:Negative )?[Tt]emplate:", line)), -1
        )
        if template_index > 0:
            templates = re.split(r"^Negative template:", "\n".join(prompt_lines[template_index:]), flags=re.M)
            metadata["Template"] = js_trim(re.sub(r"^Template:\s*", "", templates[0]))
            if len(templates) > 1:
                metadata["Negative template"] = js_trim(templates[1])
            prompt_lines = prompt_lines[:template_index]
        prompts = "\n".join(prompt_lines).split("Negative prompt:")
        if len(prompts) > 2:
            raise ParserError("found multiple negative prompts")
        prompt = js_trim(prompts[0])
        negative_prompt = js_trim(prompts[1]) if len(prompts) > 1 else ""

        # SD.Next leaves the sampler out when the default one was used
        sampler_name = sampler_info.pop("Sampler", None)
        if sampler_name is None:
            sampler_name = "unknown"

        model_name = metadata.pop("Model", None)
        model_hash = metadata.pop("Model hash", None)
        model = Model(name=model_name, hash=model_hash) if model_name or model_hash else None

        sampler = Sampler(
            sampler_name,
            self.normalize_parameters(sampler_info, REPLACEMENT_RULES),
            model=model,
            prompts=[Prompt(prompt)] if prompt else [],
            negative_prompts=[Prompt(negative_prompt)] if negative_prompt else [],
        )
        return PromptInfo(self.generator, [sampler], metadata, parameters)


def _get_sampler_info(lines: List[str]) -> Tuple[int, Dict[str, Any], Dict[str, Any]]:
    """Find the line holding the sampler information, searching from the end of the parameter string"""
    for index in range(len(lines) - 1, -1, -1):
        metadata = extract_metadata(lines[index])
        sampler_info = dict(pop_keys(SAMPLER_PARAMS, metadata))
        if len(sampler_info) >= 3:
            return index, sampler_info, metadata
    raise ParserError("no sampler information found")


def extract_metadata(line: str) -> Dict[str, Any]:
    """Extract the `key: value` pairs of a parameter line.

    Values may be quoted (`Lora hashes: "a: 1, b: 2"`) or hold JSON (`Hashes: {...}`,
    `Civitai resources: [...]`); quoted values are unquoted, JSON values decoded.
    """
    metadata: Dict[str, Any] = {}
    index = 0
    while index < len(line):
        key = _KEY.match(line, index)
        if not key:
            # not a key: skip to the next comma
            following = line.find(",", index)
            if following == -1:
                break
            index = following + 1
            continue

        value_start = key.end()
        opening = line[value_start] if value_start < len(line) else ""
        value_end = _find_closing(line, value_start) if opening in ('"', "{", "[") and opening else -1

        if value_end != -1:
            raw = line[value_start : value_end + 1]
            try:
                value: Any = json.loads(raw) if opening == '"' else load_json(raw)
            except ValueError:
                value = raw[1:-1] if opening == '"' else raw
            index = value_end + 1
            comma = line.find(",", index)
            index = len(line) if comma == -1 else comma + 1
        else:
            comma = line.find(",", value_start)
            end = len(line) if comma == -1 else comma
            raw = js_trim(line[value_start:end])
            index = end + 1
            # a value holding `: ` belongs to an unquoted list, which can't be read reliably
            if re.search(r":\s", raw):
                continue
            value = raw

        metadata[js_trim(key.group(1))] = value
    return metadata


def _find_closing(text: str, start: int) -> int:
    """The index of the quote or bracket closing the one at `start`, or -1"""
    opening = text[start]
    if opening == '"':
        i = start + 1
        while i < len(text):
            if text[i] == "\\":
                i += 1
            elif text[i] == '"':
                return i
            i += 1
        return -1

    stack: List[str] = []
    in_string = False
    i = start
    while i < len(text):
        char = text[i]
        if in_string:
            if char == "\\":
                i += 1
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
        elif char in "{[":
            stack.append("}" if char == "{" else "]")
        elif char in "}]":
            if not stack or stack.pop() != char:
                return -1
            if not stack:
                return i
        i += 1
    return -1
