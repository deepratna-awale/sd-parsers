"""ComfyUI node graphs."""

from __future__ import annotations

import logging
from typing import Any, Dict, Generator, Iterable, List, Optional, Tuple

from .._util import is_dict, js_items, js_str, js_trim, load_json
from ..data import Generators, Model, Prompt, PromptInfo, Sampler
from ..exceptions import ParserError
from ._base import Parser

logger = logging.getLogger(__name__)

SAMPLER_TYPES = ["WanVideoSampler"]
SAMPLER_PARAMS = ["sampler_name", "steps", "cfg"]
REPLACEMENT_RULES = [("cfg", "cfg_scale")]

#: Text inputs of prompt nodes: CLIPTextEncode and the text, string and prompt nodes of popular node packs
TEXT_KEYS = ["text", "Text", "prompt", "text_g", "text_l", "value", "string"]
POSITIVE_PROMPT_KEYS = TEXT_KEYS + ["positive"]
NEGATIVE_PROMPT_KEYS = TEXT_KEYS + ["negative"]
#: Samplers that take their settings from separate guider, sampler, sigmas and noise nodes
CUSTOM_SAMPLER_TYPES = ["SamplerCustomAdvanced", "SamplerCustom"]
CUSTOM_SAMPLER_INPUTS = ["guider", "sampler", "sigmas", "noise"]
IGNORE_LINK_TYPES_PROMPT = ["CLIP"]
IGNORE_CLASS_TYPES = ["ConditioningCombine"]
#: Link types of well-known inputs, for links read from the prompt (it does not record types)
PROMPT_LINK_TYPES = {"clip": "CLIP", "model": "MODEL", "vae": "VAE"}

TraverseItem = Tuple[Any, Any, List[Any]]


def _hashable(value: Any) -> Any:
    try:
        hash(value)
        return value
    except TypeError:
        return js_str(value)


def _lookup(mapping: Dict[Any, Any], key: Any) -> Any:
    try:
        return mapping.get(key)
    except TypeError:
        return None


def _contains(mapping: Any, key: Any) -> bool:
    try:
        return key in mapping
    except TypeError:
        return False


def link_target(value: Any) -> Any:
    """The id of the node an input is linked to (the first element of a `[node_id, slot]` link)"""
    if isinstance(value, (list, str)) and len(value) > 0:
        return value[0]
    return None


def _py_str(value: Any) -> str:
    """Python's `str()` for the JSON values used as node ids"""
    if value is None:
        return "None"
    if value is True:
        return "True"
    if value is False:
        return "False"
    return js_str(value)


def _key(value: Any) -> str:
    return value if isinstance(value, str) else js_str(value)


class ComfyUIParser(Parser):
    """Parser for images generated by ComfyUI"""

    generator = Generators.COMFYUI

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        workflow: Any = None
        has_workflow = False
        try:
            if "prompt" not in parameters:
                raise ValueError("prompt missing")
            prompt_value = parameters["prompt"]
            if is_dict(prompt_value):
                prompt = js_items(prompt_value)
            else:
                decoded = load_json(prompt_value)
                if not is_dict(decoded):
                    raise TypeError("JSON value is not an object")
                prompt = list(decoded.items())
            if "workflow" in parameters:
                has_workflow = True
                workflow = parameters["workflow"] if is_dict(parameters["workflow"]) else load_json(parameters["workflow"])
        except (ValueError, TypeError) as error:
            raise ParserError(f"error reading parameters: {error}") from error

        if not any(is_dict(node) and "class_type" in node and is_dict(node.get("inputs")) for _, node in prompt):
            raise ParserError("prompt holds no nodes")

        samplers, metadata = _ImageContext.extract(self, prompt, workflow if has_workflow else _NO_WORKFLOW)
        return PromptInfo(self.generator, samplers, metadata, parameters)


_NO_WORKFLOW = object()


class _ImageContext:
    def __init__(self, parser: ComfyUIParser, prompt: List[Tuple[str, Any]], workflow: Any) -> None:
        self.parser = parser
        self.processed_nodes: set = set()
        self.prompt: Dict[str, Any] = {str(key): value for key, value in prompt}
        #: input id -> {output id: set of link types}
        self.links: Dict[Any, Dict[Any, set]] = {}

        if workflow is not _NO_WORKFLOW:
            links = workflow.get("links") if is_dict(workflow) else None
            if not isinstance(links, list):
                raise ParserError("workflow has unexpected format")
            for link in links:
                if not isinstance(link, list) or len(link) != 6:
                    raise ParserError("workflow has unexpected format")
                _, output_id, _, input_id, _, link_type = link
                self._add_link(_py_str(input_id), _py_str(output_id), link_type)

        # the links of the prompt itself: they are always present, and still match the node ids
        # when the workflow uses other ones (group nodes, subgraphs, other tools' workflows)
        for node_id, node in self.prompt.items():
            if not is_dict(node) or not is_dict(node.get("inputs")):
                continue
            for input_name, value in js_items(node["inputs"]):
                target = link_target(value)
                if isinstance(value, list) and len(value) == 2 and target is not None and js_str(target) in self.prompt:
                    self._add_link(node_id, js_str(target), PROMPT_LINK_TYPES.get(input_name, "*"))

    def _add_link(self, input_id: Any, output_id: Any, link_type: Any) -> None:
        outputs = self.links.setdefault(input_id, {})
        outputs.setdefault(output_id, set()).add(_hashable(link_type))

    def _get_links(self, node_id: Any) -> Dict[Any, set]:
        return _lookup(self.links, node_id) or {}

    @classmethod
    def extract(cls, parser: ComfyUIParser, prompt: List[Tuple[str, Any]], workflow: Any) -> Tuple[List[Sampler], Dict[str, Any]]:
        context = cls(parser, prompt, workflow)
        samplers: List[Sampler] = []
        metadata: Dict[str, List[Dict[str, Any]]] = {}

        # Pass 1: samplers and related data
        for node_id, node in context.prompt.items():
            sampler = context._try_get_sampler(node_id, node)
            if sampler:
                samplers.append(sampler)

        # Pass 2: information from unprocessed nodes goes into the metadata
        for node_id, node in context.prompt.items():
            if node_id in context.processed_nodes:
                continue
            if not is_dict(node) or "inputs" not in node or "class_type" not in node:
                continue
            inputs = context._get_input_values(node["inputs"], node_id)
            if inputs:
                metadata.setdefault(_key(node["class_type"]), []).append(inputs)

        return samplers, metadata

    def _try_step_into(self, node_inputs: Dict[str, Any], node_names: Iterable[str]) -> Dict[str, Any]:
        """The inputs of the first node linked through one of the given inputs, or the original inputs"""
        for name in node_names:
            target_id = link_target(node_inputs.get(name))
            if target_id is None:
                continue
            target = _lookup(self.prompt, target_id)
            if is_dict(target) and is_dict(target.get("inputs")):
                return dict(target["inputs"])
        return node_inputs

    def _try_get_sampler(self, node_id: str, node: Any) -> Optional[Sampler]:
        if not is_dict(node) or not is_dict(node.get("inputs")) or "class_type" not in node:
            return None

        inputs = dict(node["inputs"])
        class_type = node["class_type"]
        is_custom = _contains(CUSTOM_SAMPLER_TYPES, class_type)
        setting_nodes = self._merge_custom_sampler_inputs(inputs) if is_custom else []
        # custom samplers with a BasicGuider have no cfg
        if not is_custom and not _contains(SAMPLER_TYPES, class_type) and not all(key in inputs for key in SAMPLER_PARAMS):
            return None
        self.processed_nodes.update(setting_nodes)
        logger.debug("found sampler #%s", node_id)
        self.processed_nodes.add(node_id)

        sampler_name: Any = "unknown"
        for key in ("sampler_name", "scheduler"):
            if key in inputs:
                sampler_name = inputs.pop(key)
                break
        sampler_parameters = self.parser.normalize_parameters(self._get_input_values(inputs), REPLACEMENT_RULES)

        model = None
        model_id = link_target(inputs.get("model"))
        if model_id is not None:
            model = self._get_model(model_id)

        # WanVideoSampler's TextEmbed node
        prompt_inputs = self._try_step_into(inputs, ["text_embeds"])

        prompts: List[Prompt] = []
        # BasicGuider takes a single conditioning input
        positive = prompt_inputs.get("positive")
        if positive is None:
            positive = prompt_inputs.get("conditioning")
        positive_id = link_target(positive)
        if positive_id is not None:
            prompts = self._get_prompts(positive_id, POSITIVE_PROMPT_KEYS)

        negative_prompts: List[Prompt] = []
        negative_id = link_target(prompt_inputs.get("negative"))
        if negative_id is not None:
            negative_prompts = self._get_prompts(negative_id, NEGATIVE_PROMPT_KEYS)

        return Sampler(sampler_name, sampler_parameters, sampler_id=node_id, model=model, prompts=prompts, negative_prompts=negative_prompts)

    def _merge_custom_sampler_inputs(self, inputs: Dict[str, Any]) -> List[str]:
        """Add the inputs of the guider, sampler, sigmas and noise nodes of a custom sampler to its own inputs"""
        merged: List[str] = []
        for name in CUSTOM_SAMPLER_INPUTS:
            target_id = link_target(inputs.get(name))
            target = None if target_id is None else self.prompt.get(js_str(target_id))
            if not is_dict(target) or not is_dict(target.get("inputs")):
                continue
            inputs.pop(name, None)
            merged.append(js_str(target_id))
            for key, value in target["inputs"].items():
                if key not in inputs:
                    inputs[key] = value
        if "noise_seed" in inputs and "seed" not in inputs:
            inputs["seed"] = inputs.pop("noise_seed")
        return merged

    def _get_model(self, initial_node_id: Any) -> Optional[Model]:
        """The first model reached from the given node id"""
        for node_id, node, trace in self._traverse(initial_node_id):
            if not is_dict(node) or not is_dict(node.get("inputs")):
                continue
            inputs = dict(node["inputs"])
            # `model` is also the name of the link input of LoRA loaders and patches: only names count
            key = next((k for k in ("ckpt_name", "unet_name", "model") if isinstance(inputs.get(k), str)), None)
            if key is None:
                continue
            ckpt_name = inputs.pop(key)
            self.processed_nodes.add(node_id)
            metadata = {**self._get_input_values(inputs), **self._get_trace_metadata(trace)}
            return Model(name=ckpt_name, model_id=node_id, metadata=metadata)
        return None

    def _get_prompts(self, initial_node_id: Any, text_keys: List[str]) -> List[Prompt]:
        """All prompts reachable from a given node id"""
        prompts: List[Prompt] = []

        def check_inputs(node_id: Any, inputs: Dict[str, Any], trace: List[Any]) -> bool:
            found = False
            for key in text_keys:
                if key not in inputs:
                    continue
                text = inputs.pop(key)
                if isinstance(text, str):
                    metadata = {**self._get_input_values(inputs), **self._get_trace_metadata(trace)}
                    prompts.append(Prompt(js_trim(text), prompt_id=node_id, metadata=metadata))
                    found = True
            if found:
                self.processed_nodes.add(_hashable(node_id))
                self.processed_nodes.update(_hashable(item) for item in trace)
                return False
            return True

        iterator = self._traverse(initial_node_id, IGNORE_LINK_TYPES_PROMPT)
        try:
            item = next(iterator)
            while True:
                node_id, node, trace = item
                recurse = True
                if is_dict(node) and "inputs" in node:
                    recurse = check_inputs(node_id, dict(node["inputs"]) if is_dict(node["inputs"]) else {}, trace)
                item = iterator.send(recurse)
        except StopIteration:
            pass
        return prompts

    def _traverse(self, node_id: Any, ignored_link_types: Iterable[str] = ()) -> Generator[TraverseItem, Optional[bool], None]:
        """Traverse backwards through the node tree. Sending False stops it from descending into
        the inputs of the current node."""
        visited: set = set()
        ignore = set(ignored_link_types)

        def inner(current: Any, trace: List[Any]) -> Generator[TraverseItem, Optional[bool], None]:
            visited.add(_hashable(current))
            if _contains(self.prompt, current):
                recurse = yield (current, self.prompt[current], trace[:-1])
                if recurse is False:
                    return
            for link_id, link_types in list(self._get_links(current).items()):
                if link_id not in visited and any(link_type not in ignore for link_type in link_types):
                    yield from inner(link_id, trace + [link_id])

        return inner(node_id, [node_id])

    def _get_trace_metadata(self, trace: List[Any]) -> Dict[str, Any]:
        metadata: Dict[str, Any] = {}
        for node_id in trace:
            node = _lookup(self.prompt, node_id)
            if not is_dict(node) or "class_type" not in node or "inputs" not in node:
                continue
            class_type = node["class_type"]
            if _contains(IGNORE_CLASS_TYPES, class_type):
                continue
            value = self._get_input_values(node["inputs"], node_id)
            key = _key(class_type)
            if key in metadata:
                entry = metadata[key]
                if isinstance(entry, list):
                    entry.append(value)
                else:
                    metadata[key] = [entry, value]
            else:
                metadata[key] = value
        return metadata

    def _get_input_values(self, inputs: Any, node_id: Optional[str] = None) -> Dict[str, Any]:
        if not is_dict(inputs):
            return {}
        values = {key: value for key, value in inputs.items() if not isinstance(value, list)}
        if not values:
            return {}
        return values if node_id is None else {"id": node_id, **values}
