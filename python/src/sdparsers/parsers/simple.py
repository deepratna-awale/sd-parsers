def _seed_from_graph(prompt: Any) -> Optional[Any]:
    """TensorArt writes -1 as seed when it was random; the node graph has the real one"""
    if not isinstance(prompt, str):
        return None
    try:
        graph = load_json(prompt)
    except (ValueError, TypeError):
        return None
    for node in js_values(graph) if is_dict(graph) else []:
        if is_dict(node) and is_dict(node.get("inputs")):
            inputs = node["inputs"]
            seed = _coalesce(inputs.get("seed"), inputs.get("noise_seed"))
            if is_number(seed):
                return seed
    return None


class TensorArtParser(Parser):
    """Parser for TensorArt, which writes its settings as JSON to a `generation_data` chunk"""

    generator = Generators.TENSORART
    SAMPLER_PARAMS = ["seed", "steps", "cfgScale", "schedule", "clipSkip", "denoisingStrength"]
    REPLACEMENT_RULES = [
        ("cfgScale", "cfg_scale"),
        ("schedule", "scheduler"),
        ("clipSkip", "clip_skip"),
        ("denoisingStrength", "denoising_strength"),
    ]

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        if "generation_data" not in parameters:
            raise ParserError("no generation_data found")
        params = read_json_object(parameters["generation_data"], "generation_data")

        sampler_name = take(params, "ksamplerName")
        if sampler_name is None:
            sampler_name = _coalesce(take(params, "samplerName"), "unknown")
        prompt = take(params, "prompt")
        negative_prompt = take(params, "negativePrompt")

        model = None
        base_model = take(params, "baseModel")
        if is_dict(base_model) and (base_model.get("modelFileName") or base_model.get("hash")):
            rest = {k: v for k, v in base_model.items() if k not in ("modelFileName", "hash", "modelId")}
            model = Model(
                name=base_model.get("modelFileName"),
                hash=base_model.get("hash"),
                model_id=base_model.get("modelId"),
                metadata=rest,
            )

        if "seed" in params:
            params["seed"] = to_number(params["seed"])
        if is_number(params.get("seed")) and params["seed"] == -1:
            from_graph = _seed_from_graph(parameters.get("prompt"))
            if from_graph is not None:
                params["seed"] = from_graph

        sampler = Sampler(
            sampler_name,
            self.normalize_parameters(pop_keys(self.SAMPLER_PARAMS, params), self.REPLACEMENT_RULES),
            model=model,
            prompts=prompt_list(prompt),
            negative_prompts=prompt_list(negative_prompt),
        )
        return PromptInfo(self.generator, [sampler], params, parameters)


def _checkpoint_from_graph(graph: Dict[str, Any]) -> Optional[str]:
    """The checkpoint of a CivitAI node graph (an AIR such as `urn:air:sdxl:checkpoint:civitai:827184@2514310`)"""
    for node in js_values(graph):
        if is_dict(node) and is_dict(node.get("inputs")) and isinstance(node["inputs"].get("ckpt_name"), str):
            return node["inputs"]["ckpt_name"]
    return None


class CivitaiParser(Parser):
    """Parser for images generated on CivitAI with its ComfyUI based generator"""

    generator = Generators.CIVITAI
    SAMPLER_PARAMS = ["seed", "steps", "cfgScale", "clipSkip", "denoise"]
    REPLACEMENT_RULES = [("cfgScale", "cfg_scale"), ("clipSkip", "clip_skip")]

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        source = next(
            (
                value
                for value in (parameters.get("UserComment"), parameters.get("prompt"), parameters.get("parameters"))
                if isinstance(value, str) and '"extraMetadata"' in value
            ),
            None,
        )
        if not source:
            raise ParserError("no CivitAI metadata found")
        graph = read_json_object(source)
        if "extraMetadata" not in graph:
            raise ParserError("no CivitAI metadata found")
        params = read_json_object(graph["extraMetadata"], "extraMetadata")

        sampler_name = _coalesce(take(params, "sampler"), "unknown")
        prompt = take(params, "prompt")
        negative_prompt = take(params, "negativePrompt")

        checkpoint = _checkpoint_from_graph(graph)
        resources = params.get("resources") if isinstance(params.get("resources"), list) else []
        checkpoint_resource = next(
            (r for r in resources if is_dict(r) and re.search("checkpoint", js_str(r.get("type", "undefined")), re.I)),
            None,
        )
        model = Model(name=checkpoint, metadata=dict(checkpoint_resource) if checkpoint_resource else {}) if checkpoint else None

        sampler = Sampler(
            sampler_name,
            self.normalize_parameters(pop_keys(self.SAMPLER_PARAMS, params), self.REPLACEMENT_RULES),
            model=model,
            prompts=prompt_list(prompt),
            negative_prompts=prompt_list(negative_prompt),
        )
        params.pop("images", None)
        extra = graph.get("extra")
        if is_dict(extra) and isinstance(extra.get("airs"), list):
            params["airs"] = extra["airs"]
        return PromptInfo(self.generator, [sampler], params, parameters)


