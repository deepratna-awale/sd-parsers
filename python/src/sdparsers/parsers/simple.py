class NovelAIParser(Parser):
    """Parser for images generated by NovelAI"""

    generator = Generators.NOVELAI
    SAMPLER_PARAMS = ["seed", "strength", "noise", "scale"]
    REPLACEMENT_RULES = [("scale", "cfg_scale")]

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        try:
            metadata = load_json(parameters.get("Comment"))
            if "Description" not in parameters or "Source" not in parameters:
                raise ValueError("missing Description or Source")
            params = parameters["Description"]
            source = parameters["Source"]
        except (ValueError, TypeError) as error:
            raise ParserError(f"error reading parameter values: {error}") from error

        if not is_dict(metadata) or "sampler" not in metadata:
            raise ParserError("no sampler found")
        if not isinstance(params, str):
            raise ParserError("error reading parameter values: Description")

        sampler_name = metadata.pop("sampler")
        sampler_parameters = self.normalize_parameters(pop_keys(self.SAMPLER_PARAMS, metadata), self.REPLACEMENT_RULES)
        prompts = [Prompt(_clean_description(params, metadata.get("prompt")))]
        negative_prompts = [Prompt(metadata.pop("uc"))] if "uc" in metadata else []

        model = None
        match = re.match(r"(.*?)\s+([A-Z0-9]+)\Z", source) if isinstance(source, str) else None
        if match:
            model = Model(name=match.group(1), hash=match.group(2))

        sampler = Sampler(sampler_name, sampler_parameters, model=model, prompts=prompts, negative_prompts=negative_prompts)
        return PromptInfo(self.generator, [sampler], metadata, parameters)


def _clean_description(description: str, comment_prompt: Any) -> str:
    """NovelAI's WEBP files can carry a Description with leading null characters or broken UTF-8"""
    cleaned = js_trim(description.lstrip("\x00"))
    if "�" in cleaned and isinstance(comment_prompt, str):
        return js_trim(comment_prompt)
    return cleaned


