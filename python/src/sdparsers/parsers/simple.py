def _coalesce(*values: Any) -> Any:
    for value in values:
        if value is not None:
            return value
    return None


class FooocusParser(Parser):
    """Parser for images generated by Fooocus"""

    generator = Generators.FOOOCUS
    SAMPLER_PARAMS = ["guidance_scale", "scheduler", "seed", "sharpness", "steps"]
    REPLACEMENT_RULES = [("guidance_scale", "cfg_scale")]

    def parse(self, raw_parameters: Dict[str, Any]) -> PromptInfo:
        try:
            parameters = load_json(raw_parameters.get("parameters"))
        except (ValueError, TypeError) as error:
            raise ParserError(f"error decoding parameter data: {error}") from error
        if not is_dict(parameters):
            raise ParserError("error decoding parameter data")
        # diffusers parameter names, as written by Hugging Face Spaces
        if "num_inference_steps" in parameters:
            raise ParserError("not a Fooocus image")

        def pop(key: str) -> Any:
            if key not in parameters:
                raise ParserError(f"error reading parameter value: {key}")
            return parameters.pop(key)

        # the model hash and negative prompt are not always written, don't reject the image because of that
        name = parameters.pop("base_model", None)
        hash_ = parameters.pop("base_model_hash", None)
        model = Model(name=name, hash=hash_) if name is not None or hash_ is not None else None

        sampler_parameters = self.normalize_parameters(pop_keys(self.SAMPLER_PARAMS, parameters), self.REPLACEMENT_RULES)
        sampler_name = pop("sampler")
        prompts = [Prompt(pop("prompt"))]
        negative_prompt = parameters.pop("negative_prompt", None)
        negative_prompts = [Prompt(negative_prompt)] if negative_prompt else []

        sampler = Sampler(sampler_name, sampler_parameters, model=model, prompts=prompts, negative_prompts=negative_prompts)
        return PromptInfo(self.generator, [sampler], parameters, raw_parameters)


class SwarmUIParser(Parser):
    """Parser for images generated by SwarmUI, which writes a `sui_image_params` JSON object"""

    generator = Generators.SWARMUI
    SAMPLER_PARAMS = ["seed", "steps", "cfgscale", "scheduler", "denoising_strength"]
    REPLACEMENT_RULES = [("cfgscale", "cfg_scale")]

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        source = next(
            (
                value
                for value in (parameters.get("parameters"), parameters.get("UserComment"))
                if isinstance(value, str) and "sui_image_params" in value
            ),
            None,
        )
        if not source:
            raise ParserError("no SwarmUI parameters found")
        data = read_json_object(source)
        if not is_dict(data.get("sui_image_params")):
            raise ParserError("no SwarmUI parameters found")

        params = dict(data["sui_image_params"])
        sampler_name = _coalesce(take(params, "sampler"), "unknown")
        prompt = take(params, "prompt")
        negative_prompt = take(params, "negativeprompt")
        model_name = take(params, "model")

        models = data.get("sui_models") if isinstance(data.get("sui_models"), list) else []
        model_info = next((entry for entry in models if is_dict(entry) and entry.get("param") == "model"), None)
        model = None
        if model_name or (model_info and model_info.get("name")):
            model = Model(
                name=_coalesce(model_name, model_info.get("name") if model_info else None),
                hash=model_info.get("hash") if model_info else None,
            )

        sampler = Sampler(
            sampler_name,
            self.normalize_parameters(pop_keys(self.SAMPLER_PARAMS, params), self.REPLACEMENT_RULES),
            model=model,
            prompts=prompt_list(prompt),
            negative_prompts=prompt_list(negative_prompt),
        )
        metadata = dict(params)
        if is_dict(data.get("sui_extra_data")):
            metadata["sui_extra_data"] = data["sui_extra_data"]
        if models:
            metadata["sui_models"] = models
        return PromptInfo(self.generator, [sampler], metadata, parameters)


_EASY_DIFFUSION_MARKER = "use_stable_diffusion_model"


def _from_python_literal(value: Any) -> Any:
    """Parse the Python literals Easy Diffusion writes into PNG text chunks"""
    if not isinstance(value, str):
        return value
    if value == "None":
        return None
    if value == "True":
        return True
    if value == "False":
        return False
    if re.fullmatch(r"\[.*\]", value, re.S):
        try:
            return load_json(value.replace("'", '"'))
        except ValueError:
            return value
    return to_number(value)


class EasyDiffusionParser(Parser):
    """Parser for images generated by Easy Diffusion"""

    generator = Generators.EASYDIFFUSION
    SAMPLER_PARAMS = ["seed", "num_inference_steps", "guidance_scale", "scheduler_name", "prompt_strength"]
    REPLACEMENT_RULES = [
        ("num_inference_steps", "steps"),
        ("guidance_scale", "cfg_scale"),
        ("scheduler_name", "scheduler"),
    ]

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        if _EASY_DIFFUSION_MARKER in parameters:
            params = {key: _from_python_literal(value) for key, value in parameters.items()}
            params.pop("UserComment", None)
        else:
            source = next(
                (
                    value
                    for value in (parameters.get("UserComment"), parameters.get("parameters"))
                    if isinstance(value, str) and _EASY_DIFFUSION_MARKER in value
                ),
                None,
            )
            if not source:
                raise ParserError("no Easy Diffusion parameters found")
            params = read_json_object(source)
        if _EASY_DIFFUSION_MARKER not in params:
            raise ParserError("no Easy Diffusion parameters found")

        sampler_name = _coalesce(take(params, "sampler_name"), "unknown")
        prompt = take(params, "prompt")
        negative_prompt = take(params, "negative_prompt")
        model_name = take(params, _EASY_DIFFUSION_MARKER)
        model = Model(name=js_str(model_name)) if model_name else None

        sampler_parameters = {key: value for key, value in pop_keys(self.SAMPLER_PARAMS, params) if value is not None}
        sampler = Sampler(
            sampler_name,
            self.normalize_parameters(sampler_parameters, self.REPLACEMENT_RULES),
            model=model,
            prompts=prompt_list(prompt),
            negative_prompts=prompt_list(negative_prompt),
        )
        metadata = {key: value for key, value in params.items() if value is not None and value != ""}
        return PromptInfo(self.generator, [sampler], metadata, parameters)


