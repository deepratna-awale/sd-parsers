class DezgoParser(Parser):
    """Parser for images generated by Dezgo"""

    generator = Generators.DEZGO
    SAMPLER_PARAMS = ["seed", "steps", "guidance", "strength"]
    REPLACEMENT_RULES = [("guidance", "cfg_scale")]

    def parse(self, parameters: Dict[str, Any]) -> PromptInfo:
        gen_info = parameters.get("GenInfo")
        user_comment = parameters.get("UserComment")
        if isinstance(gen_info, str):
            job = read_json_object(gen_info, "GenInfo")
        elif isinstance(user_comment, str) and re.search(r"^\s*JobId:", user_comment, re.M):
            job = parse_simple_yaml(user_comment)
        else:
            raise ParserError("no Dezgo job found")
        if not is_dict(job.get("Input")) or "JobId" not in job:
            raise ParserError("no Dezgo job found")

        inputs = dict(job["Input"])
        sampler_name = _coalesce(take(inputs, "sampler"), "unknown")
        prompt = take(inputs, "prompt")
        negative_prompt = take(inputs, "negative_prompt")
        model_name = take(inputs, "model")
        model = Model(name=js_str(model_name)) if model_name else None

        sampler = Sampler(
            sampler_name,
            self.normalize_parameters(pop_keys(self.SAMPLER_PARAMS, inputs), self.REPLACEMENT_RULES),
            model=model,
            prompts=prompt_list(prompt),
            negative_prompts=prompt_list(negative_prompt),
        )
        metadata = {**inputs, "job_id": job["JobId"]}
        if job.get("Function") is not None or "Function" in job:
            metadata["function"] = job.get("Function")
        return PromptInfo(self.generator, [sampler], metadata, parameters)


