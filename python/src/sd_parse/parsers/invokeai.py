"""InvokeAI, in its three metadata formats."""

from __future__ import annotations

import re
from typing import Any, Callable, Dict, List, Optional

from .._util import is_dict, load_json
from ..data import Generators, Model, Prompt, PromptInfo, Sampler
from ..exceptions import ParserError
from ._base import Parser, pop_keys

SAMPLER_PARAMS = ["cfg_scale", "cfg_rescale_multiplier", "perlin", "seed", "steps", "threshold"]

DREAM_KEYS: Dict[str, tuple] = {
    "A": ("sampler", None),
    "C": ("cfg_scale", float),
    "H": ("height", int),
    "s": ("steps", int),
    "S": ("seed", int),
    "W": ("width", int),
}


class _MissingVariant(Exception):
    """A variant's metadata key is missing, so the next variant is tried"""


class InvokeAIParser(Parser):
    """Parser for images generated by InvokeAI"""

    generator = Generators.INVOKEAI

    def parse(self, metadata: Dict[str, Any]) -> PromptInfo:
        for read_parameters, parse in _VARIANTS:
            try:
                parameters = read_parameters(metadata)
            except _MissingVariant:
                continue
            return parse(self, parameters)
        raise ParserError("no sampler found")


def _require(dictionary: Dict[str, Any], key: str) -> Any:
    if key not in dictionary:
        raise _MissingVariant(key)
    return dictionary[key]


def _get_sampler(parser: InvokeAIParser, metadata: Any, key: str) -> Sampler:
    if not is_dict(metadata):
        raise ParserError("no sampler found")
    parameters = parser.normalize_parameters(pop_keys(SAMPLER_PARAMS, metadata))
    if key not in metadata:
        raise ParserError("no sampler found")
    return Sampler(metadata.pop(key), parameters)


def _add_prompts(sampler: Sampler, combined_prompt: Any, metadata: Dict[str, Any]) -> None:
    if not isinstance(combined_prompt, str):
        raise ParserError("malformed prompt information")

    def get_prompt(prompt_id: str, text: str) -> Optional[Prompt]:
        stripped = text.strip(" ,")
        return Prompt(stripped, prompt_id=prompt_id, metadata=metadata) if stripped else None

    prompt_index = 0
    i = 0
    for match in re.finditer(r"\[([^\[]*)\]", combined_prompt):
        i += 1
        negative = get_prompt(str(i), match.group(0)[1:-1])
        if negative:
            sampler.negative_prompts.append(negative)
        if match.start() > prompt_index:
            prompt = get_prompt(str(i), combined_prompt[prompt_index : match.start()])
            if prompt:
                sampler.prompts.append(prompt)
        prompt_index = match.end()

    if prompt_index < len(combined_prompt):
        prompt = get_prompt(str(i + 1), combined_prompt[prompt_index:])
        if prompt:
            sampler.prompts.append(prompt)


def _parse_sd_metadata(parser: InvokeAIParser, parameters: Dict[str, Any]) -> PromptInfo:
    """Images with a `sd-metadata` field"""
    try:
        metadata = load_json(parameters["sd-metadata"])
    except (ValueError, TypeError) as error:
        raise ParserError(f"error reading metadata: {error}") from error
    if not is_dict(metadata) or "image" not in metadata:
        raise ParserError("no image entry found")
    image = metadata.pop("image")

    sampler = _get_sampler(parser, image, "sampler")

    if "prompt" not in image:
        raise ParserError("no prompt entry found")
    prompts = image.pop("prompt")
    if not isinstance(prompts, list):
        raise ParserError("malformed prompt information")
    for item in prompts:
        if not is_dict(item):
            raise ParserError("malformed prompt information")
        if "prompt" not in item:
            continue
        text = item.pop("prompt")
        _add_prompts(sampler, text, item)

    model_name = metadata.pop("model_weights", None)
    model_hash = metadata.pop("model_hash", None)
    if model_name or model_hash:
        sampler.model = Model(name=model_name, hash=model_hash)

    return PromptInfo(parser.generator, [sampler], {**metadata, **image}, parameters)


def _parse_dream(parser: InvokeAIParser, parameters: Dict[str, Any]) -> PromptInfo:
    """Images generated by legacy InvokeAI"""
    dream = parameters.get("Dream")
    match = re.match(r'"(.*?)"(.*)\Z', dream) if isinstance(dream, str) else None
    if not match:
        raise ParserError("could not read generation parameters")
    prompts, args = match.group(1), match.group(2)

    metadata: Dict[str, Any] = {}
    for arg in re.finditer(r"\s+-(\w+)\s+(\S+)", args):
        key, value = arg.group(1), arg.group(2)
        try:
            if key not in DREAM_KEYS:
                raise ValueError("unknown key")
            name, convert = DREAM_KEYS[key]
            metadata[name] = convert(value) if convert else value
        except ValueError:
            metadata[key] = value

    sampler = _get_sampler(parser, metadata, "sampler")
    _add_prompts(sampler, prompts, {})
    return PromptInfo(parser.generator, [sampler], metadata, parameters)


def _parse_invokeai_meta(parser: InvokeAIParser, parameters: Dict[str, Any]) -> PromptInfo:
    """The newest InvokeAI metadata format"""
    try:
        metadata = load_json(parameters.get("invokeai_metadata"))
    except (ValueError, TypeError) as error:
        raise ParserError(f"error reading metadata: {error}") from error
    if not is_dict(metadata):
        raise ParserError("error reading metadata")

    sampler = _get_sampler(parser, metadata, "scheduler")

    if "positive_prompt" in metadata:
        prompt = metadata.pop("positive_prompt")
        if prompt != "":
            sampler.prompts = [Prompt(prompt)]
    if "negative_prompt" in metadata:
        prompt = metadata.pop("negative_prompt")
        if prompt != "":
            sampler.negative_prompts = [Prompt(prompt)]

    if "model" in metadata:
        model_info = metadata.pop("model")
        if is_dict(model_info) and model_info.get("model_name") is not None:
            name = model_info.pop("model_name")
            sampler.model = Model(name=name, metadata=model_info)

    return PromptInfo(parser.generator, [sampler], metadata, parameters)


_VARIANTS: List[tuple] = [
    (lambda m: {"sd-metadata": _require(m, "sd-metadata")}, _parse_sd_metadata),
    (lambda m: {"Dream": _require(m, "Dream")}, _parse_dream),
    (lambda m: {key: m[key] for key in ("invokeai_metadata", "invokeai_graph") if key in m}, _parse_invokeai_meta),
]
