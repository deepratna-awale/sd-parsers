import { Parser, popKeys, hasKey, isDict } from './parser';
import { Generators, createPromptInfo, createSampler, createModel, createPrompt, PromptInfo, Prompt, Model } from '../data';
import { ParserError } from '../exceptions';
import { loadJson } from '../utils/json';

const SAMPLER_PARAMS = ['cfg_scale', 'cfg_rescale_multiplier', 'perlin', 'seed', 'steps', 'threshold'];

const DREAM_KEYS: Record<string, [string, ((value: string) => number) | null]> = {
  A: ['sampler', null],
  C: ['cfg_scale', pyFloat],
  H: ['height', pyInt],
  s: ['steps', pyInt],
  S: ['seed', pyInt],
  W: ['width', pyInt],
};

/** Raised by a variant when its metadata key is missing, so that the next variant is tried. */
class MissingVariant extends Error {}

interface SamplerData {
  name: string;
  parameters: Record<string, any>;
  model?: Model;
  prompts: Prompt[];
  negativePrompts: Prompt[];
}

type VariantParser = {
  parse: (parser: InvokeAIParser, parameters: Record<string, any>) => PromptInfo;
  readParameters: (metadata: Record<string, any>) => Record<string, any>;
};

const VARIANT_PARSERS: VariantParser[] = [
  {
    parse: parseSdMetadata,
    readParameters: m => ({ 'sd-metadata': requireKey(m, 'sd-metadata') }),
  },
  {
    parse: parseDream,
    readParameters: m => ({ Dream: requireKey(m, 'Dream') }),
  },
  {
    parse: parseInvokeAIMeta,
    readParameters: m =>
      Object.fromEntries(['invokeai_metadata', 'invokeai_graph'].filter(key => hasKey(m, key)).map(key => [key, m[key]])),
  },
];

/**
 * Parser for images generated by InvokeAI
 */
export class InvokeAIParser extends Parser {
  public readonly generator = Generators.INVOKEAI;

  async parse(metadata: Record<string, any>): Promise<PromptInfo> {
    for (const variant of VARIANT_PARSERS) {
      try {
        const parameters = variant.readParameters(metadata);
        return variant.parse(this, parameters);
      } catch (error) {
        if (error instanceof MissingVariant) {
          continue;
        }
        throw error;
      }
    }

    throw new ParserError('no sampler found');
  }
}

function requireKey(dictionary: Record<string, any>, key: string): any {
  if (!hasKey(dictionary, key)) {
    throw new MissingVariant(key);
  }
  return dictionary[key];
}

/**
 * Read generation parameters for an image containing a `sd-metadata` field
 */
function parseSdMetadata(parser: InvokeAIParser, parameters: Record<string, any>): PromptInfo {
  let metadata: Record<string, any>;
  try {
    metadata = loadJson(parameters['sd-metadata']);
  } catch (error) {
    throw new ParserError(`error reading metadata: ${error}`);
  }

  if (!isDict(metadata) || !hasKey(metadata, 'image')) {
    throw new ParserError('no image entry found');
  }
  const metadataImage = metadata.image;
  delete metadata.image;

  // sampler
  const sampler = getSampler(parser, metadataImage, 'sampler');

  // prompts
  if (!hasKey(metadataImage, 'prompt')) {
    throw new ParserError('no prompt entry found');
  }
  const prompts = metadataImage.prompt;
  delete metadataImage.prompt;

  if (prompts === null || typeof prompts !== 'object' || !(Symbol.iterator in prompts)) {
    throw new ParserError('malformed prompt information');
  }
  for (const promptItem of prompts) {
    if (!isDict(promptItem)) {
      throw new ParserError('malformed prompt information');
    }
    if (!hasKey(promptItem, 'prompt')) {
      continue;
    }
    const promptText = promptItem.prompt;
    delete promptItem.prompt;
    addPrompts(sampler, promptText, promptItem);
  }

  // model
  const modelName = metadata.model_weights;
  const modelHash = metadata.model_hash;
  delete metadata.model_weights;
  delete metadata.model_hash;
  if (modelName || modelHash) {
    sampler.model = createModel({ name: modelName, hash: modelHash });
  }

  return createPromptInfo(parser.generator, [toSampler(sampler)], { ...metadata, ...metadataImage }, parameters);
}

/**
 * Read generation parameters from images generated by legacy InvokeAI
 */
function parseDream(parser: InvokeAIParser, parameters: Record<string, any>): PromptInfo {
  const match = typeof parameters.Dream === 'string' ? /^"(.*?)"(.*)$/.exec(parameters.Dream) : null;
  if (!match) {
    throw new ParserError('could not read generation parameters');
  }

  const [, prompts, args] = match;

  // split args into metadata
  const metadata: Record<string, any> = {};
  for (const argMatch of args.matchAll(/\s+-([\p{L}\p{N}_]+)\s+(\S+)/gu)) {
    const [, key, value] = argMatch;

    try {
      if (!hasKey(DREAM_KEYS, key)) {
        throw new Error('unknown key');
      }
      const [keyName, convert] = DREAM_KEYS[key];
      metadata[keyName] = convert ? convert(value) : value;
    } catch {
      metadata[key] = value;
    }
  }

  // sampler
  const sampler = getSampler(parser, metadata, 'sampler');

  // prompts
  addPrompts(sampler, prompts, {});

  return createPromptInfo(parser.generator, [toSampler(sampler)], metadata, parameters);
}

/**
 * Read generation parameters from the newest InvokeAI metadata format
 */
function parseInvokeAIMeta(parser: InvokeAIParser, parameters: Record<string, any>): PromptInfo {
  let metadata: Record<string, any>;
  try {
    metadata = loadJson(parameters.invokeai_metadata);
  } catch (error) {
    throw new ParserError(`error reading metadata: ${error}`);
  }
  if (!isDict(metadata)) {
    throw new ParserError('error reading metadata');
  }

  // sampler
  const sampler = getSampler(parser, metadata, 'scheduler');

  // positive prompt
  if (hasKey(metadata, 'positive_prompt')) {
    const prompt = metadata.positive_prompt;
    delete metadata.positive_prompt;
    if (prompt !== '') {
      sampler.prompts = [createPrompt(prompt)];
    }
  }

  // negative prompt
  if (hasKey(metadata, 'negative_prompt')) {
    const prompt = metadata.negative_prompt;
    delete metadata.negative_prompt;
    if (prompt !== '') {
      sampler.negativePrompts = [createPrompt(prompt)];
    }
  }

  // model
  if (hasKey(metadata, 'model')) {
    const modelInfo = metadata.model;
    delete metadata.model;

    if (isDict(modelInfo) && hasKey(modelInfo, 'model_name') && modelInfo.model_name != null) {
      const name = modelInfo.model_name;
      delete modelInfo.model_name;
      sampler.model = createModel({ name, metadata: modelInfo });
    }
  }

  return createPromptInfo(parser.generator, [toSampler(sampler)], metadata, parameters);
}

function getSampler(parser: InvokeAIParser, metadata: Record<string, any>, key: string): SamplerData {
  if (!isDict(metadata)) {
    throw new ParserError('no sampler found');
  }

  const samplerParameters = parser.normalizeParameters(popKeys(SAMPLER_PARAMS, metadata));
  if (!hasKey(metadata, key)) {
    throw new ParserError('no sampler found');
  }
  const name = metadata[key];
  delete metadata[key];

  return { name, parameters: samplerParameters, prompts: [], negativePrompts: [] };
}

function addPrompts(sampler: SamplerData, combinedPrompt: string, metadata: Record<string, any>) {
  if (typeof combinedPrompt !== 'string') {
    throw new ParserError('malformed prompt information');
  }

  const getPrompt = (promptId: string, promptString: string): Prompt | null => {
    const promptText = stripChars(promptString, ' ,');
    return promptText ? createPrompt(promptText, { promptId, metadata }) : null;
  };

  let promptIndex = 0;
  let i = 0;
  for (const match of combinedPrompt.matchAll(/\[([^[]*)\]/g)) {
    i++;
    const negativePrompt = getPrompt(String(i), match[0].slice(1, -1));
    if (negativePrompt) {
      sampler.negativePrompts.push(negativePrompt);
    }

    const start = match.index!;
    const end = start + match[0].length;
    if (start > promptIndex) {
      const prompt = getPrompt(String(i), combinedPrompt.slice(promptIndex, start));
      if (prompt) {
        sampler.prompts.push(prompt);
      }
    }
    promptIndex = end;
  }

  if (promptIndex < combinedPrompt.length) {
    const prompt = getPrompt(String(i + 1), combinedPrompt.slice(promptIndex));
    if (prompt) {
      sampler.prompts.push(prompt);
    }
  }
}

function toSampler(sampler: SamplerData) {
  const { name, parameters, ...options } = sampler;
  return createSampler(name, parameters, options);
}

/** Equivalent of Python's `str.strip(chars)` */
function stripChars(value: string, chars: string): string {
  let start = 0;
  let end = value.length;
  while (start < end && chars.includes(value[start])) start++;
  while (end > start && chars.includes(value[end - 1])) end--;
  return value.slice(start, end);
}

/** Equivalent of Python's `int(str)` */
function pyInt(value: string): number {
  if (!/^[+-]?\d+(?:_\d+)*$/.test(value)) {
    throw new Error(`invalid literal for int(): '${value}'`);
  }
  return Number(value.replace(/_/g, ''));
}

/** Equivalent of Python's `float(str)` */
function pyFloat(value: string): number {
  const special = /^([+-]?)(inf|infinity|nan)$/i.exec(value);
  if (special) {
    if (special[2].toLowerCase() === 'nan') return NaN;
    return special[1] === '-' ? -Infinity : Infinity;
  }

  const digits = '\\d+(?:_\\d+)*';
  if (!new RegExp(`^[+-]?(?:${digits}(?:\\.(?:${digits})?)?|\\.${digits})(?:[eE][+-]?${digits})?$`).test(value)) {
    throw new Error(`could not convert string to float: '${value}'`);
  }
  return Number(value.replace(/_/g, ''));
}
