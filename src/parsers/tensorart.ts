import { Parser, ReplacementRules, popKeys, isDict } from './parser';
import { Generators, createPromptInfo, createSampler, createModel, PromptInfo, Model } from '../data';
import { ParserError } from '../exceptions';
import { readJsonObject, take, toNumber, promptList } from './helpers';
import { loadJson } from '../utils/json';

const SAMPLER_PARAMS = ['seed', 'steps', 'cfgScale', 'schedule', 'clipSkip', 'denoisingStrength'];
const REPLACEMENT_RULES: ReplacementRules = [
  ['cfgScale', 'cfg_scale'],
  ['schedule', 'scheduler'],
  ['clipSkip', 'clip_skip'],
  ['denoisingStrength', 'denoising_strength'],
];

/**
 * TensorArt writes -1 as seed when it was random; the node graph has the real one
 */
function seedFromGraph(prompt: unknown): number | undefined {
  if (typeof prompt !== 'string') return undefined;
  try {
    const graph = loadJson(prompt);
    for (const node of Object.values(isDict(graph) ? graph : {})) {
      const seed = isDict(node) && isDict(node.inputs) ? (node.inputs.seed ?? node.inputs.noise_seed) : undefined;
      if (typeof seed === 'number') return seed;
    }
  } catch {
    // keep the recorded seed
  }
  return undefined;
}

/**
 * Parser for images generated by TensorArt, which writes its settings as JSON to a
 * `generation_data` chunk, next to a ComfyUI node graph
 */
export class TensorArtParser extends Parser {
  public readonly generator = Generators.TENSORART;

  async parse(parameters: Record<string, any>): Promise<PromptInfo> {
    if (parameters.generation_data === undefined) {
      throw new ParserError('no generation_data found');
    }
    const params = readJsonObject(parameters.generation_data, 'generation_data');

    const samplerName = take(params, 'ksamplerName') ?? take(params, 'samplerName') ?? 'unknown';
    const prompt = take(params, 'prompt');
    const negativePrompt = take(params, 'negativePrompt');

    let model: Model | undefined;
    const baseModel = take(params, 'baseModel');
    if (isDict(baseModel) && (baseModel.modelFileName || baseModel.hash)) {
      const { modelFileName, hash, modelId, ...metadata } = baseModel;
      model = createModel({ name: modelFileName, hash, modelId, metadata });
    }

    params.seed = toNumber(params.seed);
    if (params.seed === -1) {
      params.seed = seedFromGraph(parameters.prompt) ?? params.seed;
    }

    const sampler = createSampler(samplerName, this.normalizeParameters(popKeys(SAMPLER_PARAMS, params), REPLACEMENT_RULES), {
      model,
      prompts: promptList(prompt),
      negativePrompts: promptList(negativePrompt),
    });

    return createPromptInfo(this.generator, [sampler], params, parameters);
  }
}
