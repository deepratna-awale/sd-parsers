import { Parser, ReplacementRules, popKeys, hasKey } from './parser';
import { Generators, createPromptInfo, createSampler, createModel, PromptInfo } from '../data';
import { ParserError } from '../exceptions';
import { readJsonObject, take, toNumber, promptList } from './helpers';

const SAMPLER_PARAMS = ['seed', 'num_inference_steps', 'guidance_scale', 'scheduler_name', 'prompt_strength'];
const REPLACEMENT_RULES: ReplacementRules = [
  ['num_inference_steps', 'steps'],
  ['guidance_scale', 'cfg_scale'],
  ['scheduler_name', 'scheduler'],
];

const MARKER = 'use_stable_diffusion_model';

/**
 * Parse the Python literals Easy Diffusion writes into PNG text chunks (`None`, `False`, `['a', 'b']`, `21`)
 */
function fromPythonLiteral(value: unknown): unknown {
  if (typeof value !== 'string') return value;
  if (value === 'None') return null;
  if (value === 'True') return true;
  if (value === 'False') return false;
  if (/^\[.*\]$/s.test(value)) {
    try {
      return JSON.parse(value.replace(/'/g, '"'));
    } catch {
      return value;
    }
  }
  return toNumber(value);
}

/**
 * Parser for images generated by Easy Diffusion
 *
 * PNG files hold one text chunk per setting, JPEG and WEBP files a JSON object in the EXIF UserComment.
 */
export class EasyDiffusionParser extends Parser {
  public readonly generator = Generators.EASYDIFFUSION;

  async parse(parameters: Record<string, any>): Promise<PromptInfo> {
    let params: Record<string, any>;
    if (hasKey(parameters, MARKER)) {
      params = Object.fromEntries(Object.entries(parameters).map(([key, value]) => [key, fromPythonLiteral(value)]));
      delete params.UserComment;
    } else {
      const source = [parameters.UserComment, parameters.parameters].find(value => typeof value === 'string' && value.includes(MARKER));
      if (!source) {
        throw new ParserError('no Easy Diffusion parameters found');
      }
      params = readJsonObject(source);
    }
    if (!hasKey(params, MARKER)) {
      throw new ParserError('no Easy Diffusion parameters found');
    }

    const samplerName = take(params, 'sampler_name') ?? 'unknown';
    const prompt = take(params, 'prompt');
    const negativePrompt = take(params, 'negative_prompt');
    const modelName = take(params, MARKER);
    const model = modelName ? createModel({ name: String(modelName) }) : undefined;

    const samplerParameters = Object.fromEntries(popKeys(SAMPLER_PARAMS, params).filter(([, value]) => value != null));
    const sampler = createSampler(samplerName, this.normalizeParameters(samplerParameters, REPLACEMENT_RULES), {
      model,
      prompts: promptList(prompt),
      negativePrompts: promptList(negativePrompt),
    });

    const metadata = Object.fromEntries(Object.entries(params).filter(([, value]) => value != null && value !== ''));
    return createPromptInfo(this.generator, [sampler], metadata, parameters);
  }
}
