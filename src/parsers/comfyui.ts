import { Parser, ReplacementRules, hasKey, isDict } from './parser';
import { Generators, createPromptInfo, createSampler, createModel, createPrompt, PromptInfo, Sampler, Model, Prompt } from '../data';
import { ParserError } from '../exceptions';
import { loadJson, loadJsonEntries } from '../utils/json';

const SAMPLER_TYPES = ['WanVideoSampler'];
const SAMPLER_PARAMS = ['sampler_name', 'steps', 'cfg'];

const REPLACEMENT_RULES: ReplacementRules = [['cfg', 'cfg_scale']];

const POSITIVE_PROMPT_KEYS = ['text', 'positive'];
const NEGATIVE_PROMPT_KEYS = ['text', 'negative'];
const IGNORE_LINK_TYPES_PROMPT = ['CLIP'];
const IGNORE_CLASS_TYPES = ['ConditioningCombine'];

type Node = Record<string, any>;
type TraverseItem = [string, Node, string[]];

/**
 * Parser for images generated by ComfyUI
 */
export class ComfyUIParser extends Parser {
  public readonly generator = Generators.COMFYUI;

  async parse(parameters: Record<string, any>): Promise<PromptInfo> {
    let prompt: [string, any][];
    let workflow: Record<string, any>;

    try {
      if (!hasKey(parameters, 'prompt') || !hasKey(parameters, 'workflow')) {
        throw new Error('prompt or workflow missing');
      }

      prompt = isDict(parameters.prompt) ? Object.entries(parameters.prompt) : loadJsonEntries(parameters.prompt);
      workflow = isDict(parameters.workflow) ? parameters.workflow : loadJson(parameters.workflow);
    } catch (error) {
      throw new ParserError(`error reading parameters: ${error}`);
    }

    const { samplers, metadata } = ImageContext.extract(this, this.debug, prompt, workflow);

    return createPromptInfo(this.generator, samplers, metadata, parameters);
  }
}

/**
 * Context class for processing ComfyUI image data
 */
class ImageContext {
  private parser: ComfyUIParser;
  private debug: boolean;
  private prompt: Map<string, Node>;
  /** Map<input_id, Map<output_id, Set<link_type>>> */
  private links: Map<string, Map<string, Set<any>>>;
  private processedNodes: Set<string>;

  constructor(parser: ComfyUIParser, debug: boolean, prompt: [string, any][], workflow: Record<string, any>) {
    this.parser = parser;
    this.debug = debug;
    this.processedNodes = new Set();
    this.prompt = new Map(prompt.map(([key, value]) => [String(key), value]));

    // build links dictionary
    this.links = new Map();
    const links = isDict(workflow) ? workflow.links : undefined;
    if (links === null || typeof links !== 'object' || !(Symbol.iterator in links)) {
      throw new ParserError('workflow has unexpected format');
    }
    for (const link of links as Iterable<any>) {
      if (!Array.isArray(link) || link.length !== 6) {
        throw new ParserError('workflow has unexpected format');
      }
      const [, outputId, , inputId, , linkType] = link;
      const outputs = this.getLinks(pyStr(inputId), true);
      const linkTypes = outputs.get(pyStr(outputId)) ?? new Set();
      outputs.set(pyStr(outputId), linkTypes.add(linkType));
    }
  }

  private getLinks(nodeId: string, create = false): Map<string, Set<any>> {
    let links = this.links.get(nodeId);
    if (!links) {
      links = new Map();
      if (create) {
        this.links.set(nodeId, links);
      }
    }
    return links;
  }

  /**
   * Extract samplers with their child parameters as well as metadata
   */
  static extract(
    parser: ComfyUIParser,
    debug: boolean,
    prompt: [string, any][],
    workflow: Record<string, any>
  ): { samplers: Sampler[]; metadata: Record<string, Record<string, any>[]> } {
    const context = new ImageContext(parser, debug, prompt, workflow);
    const samplers: Sampler[] = [];
    const metadata: Record<string, Record<string, any>[]> = {};

    // Pass 1: get samplers and related data
    for (const [nodeId, node] of context.prompt) {
      const sampler = context.tryGetSampler(nodeId, node);
      if (sampler) {
        samplers.push(sampler);
      }
    }

    // Pass 2: put information from unprocessed nodes into metadata
    for (const [nodeId, node] of context.prompt) {
      if (context.processedNodes.has(nodeId)) {
        continue;
      }

      if (!hasKey(node, 'inputs') || !hasKey(node, 'class_type')) {
        continue;
      }

      const inputs = context.getInputValues(node.inputs, nodeId);
      if (Object.keys(inputs).length > 0) {
        (metadata[node.class_type] ??= []).push(inputs);
      }
    }

    return { samplers, metadata };
  }

  /**
   * See if one of the given inputs exists in the current node
   * and return the first found node's inputs dictionary.
   *
   * If none is found, return the original inputs.
   */
  private tryStepInto(nodeInputs: Record<string, any>, nodeNames: string[]): Record<string, any> {
    for (const name of nodeNames) {
      const targetId = linkTarget(nodeInputs[name]);
      if (targetId === undefined) {
        continue;
      }
      const targetNode = this.prompt.get(targetId);
      if (isDict(targetNode) && isDict(targetNode.inputs)) {
        return { ...targetNode.inputs };
      }
    }

    return nodeInputs;
  }

  /**
   * Test if this node could contain sampler data
   */
  private tryGetSampler(nodeId: string, node: Node): Sampler | null {
    if (!isDict(node) || !isDict(node.inputs) || !hasKey(node, 'class_type')) {
      return null;
    }

    const inputs: Record<string, any> = { ...node.inputs };
    if (!SAMPLER_TYPES.includes(node.class_type) && !SAMPLER_PARAMS.every(key => hasKey(inputs, key))) {
      return null;
    }

    if (this.debug) {
      console.debug(`found sampler #${nodeId}`);
    }
    this.processedNodes.add(nodeId);

    // Sampler parameters
    let samplerName: any = 'unknown';
    for (const key of ['sampler_name', 'scheduler']) {
      if (hasKey(inputs, key)) {
        samplerName = inputs[key];
        delete inputs[key];
        break;
      }
    }
    const samplerParameters = this.parser.normalizeParameters(this.getInputValues(inputs), REPLACEMENT_RULES);

    // Model
    let model: Model | undefined;
    const modelId = linkTarget(inputs.model);
    if (modelId !== undefined) {
      model = this.getModel(modelId) ?? undefined;
    }

    // check for WanVideoSampler's TextEmbed node
    const promptInputs = this.tryStepInto(inputs, ['text_embeds']);

    // Prompt
    let prompts: Prompt[] = [];
    const positivePromptId = linkTarget(promptInputs.positive);
    if (positivePromptId !== undefined) {
      prompts = this.getPrompts(positivePromptId, POSITIVE_PROMPT_KEYS);
    }

    // Negative Prompt
    let negativePrompts: Prompt[] = [];
    const negativePromptId = linkTarget(promptInputs.negative);
    if (negativePromptId !== undefined) {
      negativePrompts = this.getPrompts(negativePromptId, NEGATIVE_PROMPT_KEYS);
    }

    return createSampler(samplerName, samplerParameters, { samplerId: nodeId, model, prompts, negativePrompts });
  }

  /**
   * Get the first model reached from the given node id
   */
  private getModel(initialNodeId: string): Model | null {
    if (this.debug) {
      console.debug(`looking for model: #${initialNodeId}`);
    }

    for (const [nodeId, node, trace] of this.traverse(initialNodeId)) {
      if (!isDict(node) || !isDict(node.inputs)) {
        continue;
      }

      const inputs: Record<string, any> = { ...node.inputs };
      const key = ['ckpt_name', 'model'].find(k => hasKey(inputs, k));
      if (key === undefined) {
        continue;
      }
      const ckptName = inputs[key];
      delete inputs[key];

      this.processedNodes.add(nodeId);
      if (this.debug) {
        console.debug(`found model #${nodeId}: ${ckptName}`);
      }

      const metadata = { ...this.getInputValues(inputs), ...this.getTraceMetadata(trace) };

      try {
        return createModel({ modelId: nodeId, name: ckptName, metadata });
      } catch {
        // neither name nor hash present
        return null;
      }
    }

    return null;
  }

  /**
   * Get all prompts reachable from a given node id
   */
  private getPrompts(initialNodeId: string, textKeys: string[]): Prompt[] {
    if (this.debug) {
      console.debug(`looking for prompts: ${initialNodeId}`);
    }

    const prompts: Prompt[] = [];

    const checkInputs = (nodeId: string, inputs: Record<string, any>, trace: string[]): boolean => {
      let foundPrompt = false;
      for (const key of textKeys) {
        if (!hasKey(inputs, key)) {
          continue;
        }
        const text = inputs[key];
        delete inputs[key];

        if (typeof text === 'string') {
          if (this.debug) {
            console.debug(`found prompt ${key}#${nodeId}: ${text}`);
          }

          const metadata = { ...this.getInputValues(inputs), ...this.getTraceMetadata(trace) };
          prompts.push(createPrompt(text.trim(), { promptId: nodeId, metadata }));
          foundPrompt = true;
        }
      }

      if (foundPrompt) {
        this.processedNodes.add(nodeId);
        trace.forEach(id => this.processedNodes.add(id));
        return false;
      }
      return true;
    };

    const promptIterator = this.traverse(initialNodeId, IGNORE_LINK_TYPES_PROMPT);
    let item = promptIterator.next();
    while (!item.done) {
      const [nodeId, node, trace] = item.value;
      let recurse = true;
      if (hasKey(node, 'inputs')) {
        recurse = checkInputs(nodeId, isDict(node.inputs) ? { ...node.inputs } : {}, trace);
      }
      item = promptIterator.next(recurse);
    }

    return prompts;
  }

  /**
   * Traverse backwards through the node tree, starting at a given node id.
   *
   * Sending `false` into the generator stops it from descending into the inputs of the current node.
   */
  private *traverse(nodeId: string, ignoredLinkTypes: string[] = []): Generator<TraverseItem, void, boolean | undefined> {
    const visited = new Set<string>();
    const ignoreLinks = new Set(ignoredLinkTypes);
    const self = this;

    function* traverseInner(nodeId: string, trace: string[]): Generator<TraverseItem, void, boolean | undefined> {
      visited.add(nodeId);

      if (self.prompt.has(nodeId)) {
        const recurse = yield [nodeId, self.prompt.get(nodeId)!, trace.slice(0, -1)];
        if (recurse === false) {
          return;
        }
      }

      for (const [linkId, linkTypes] of self.getLinks(nodeId)) {
        if (!visited.has(linkId) && [...linkTypes].some(type => !ignoreLinks.has(type))) {
          if (self.debug) {
            console.debug(`${nodeId}->${linkId}, ${'.'.repeat(trace.length)}${[...linkTypes].join(',')}`);
          }
          yield* traverseInner(linkId, [...trace, linkId]);
        }
      }
    }

    yield* traverseInner(nodeId, [nodeId]);
  }

  private getTraceMetadata(trace: string[]): Record<string, any> {
    const metadata: Record<string, any> = {};

    for (const nodeId of trace) {
      const node = this.prompt.get(nodeId);
      if (!isDict(node) || !hasKey(node, 'class_type') || !hasKey(node, 'inputs')) {
        continue;
      }

      const classType = node.class_type;
      if (IGNORE_CLASS_TYPES.includes(classType)) {
        continue;
      }

      const value = this.getInputValues(node.inputs, nodeId);

      if (hasKey(metadata, classType)) {
        const entry = metadata[classType];
        if (Array.isArray(entry)) {
          entry.push(value);
        } else {
          metadata[classType] = [entry, value];
        }
      } else {
        metadata[classType] = value;
      }
    }

    return metadata;
  }

  private getInputValues(inputs: Record<string, any>, nodeId?: string): Record<string, any> {
    if (!isDict(inputs)) {
      return {};
    }

    const values = Object.fromEntries(Object.entries(inputs).filter(([, value]) => !Array.isArray(value)));
    if (Object.keys(values).length === 0) {
      return {};
    }
    return nodeId === undefined ? values : { id: nodeId, ...values };
  }
}

/**
 * Get the id of the node an input is linked to (the first element of a `[node_id, slot]` link)
 */
function linkTarget(input: unknown): string | undefined {
  if ((Array.isArray(input) || typeof input === 'string') && input.length > 0) {
    return input[0];
  }
  return undefined;
}

/**
 * Equivalent of Python's `str()` for the JSON values used as node ids
 */
function pyStr(value: unknown): string {
  if (value === null || value === undefined) return 'None';
  if (value === true) return 'True';
  if (value === false) return 'False';
  return String(value);
}
